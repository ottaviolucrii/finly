/// The characters Windows-1252 has between 0x80 and 0x9F, which Latin-1 lacks.
const Map<int, int> _windows1252Extras = {
  0x20AC: 0x80, // €
  0x201A: 0x82, // ‚
  0x0192: 0x83, // ƒ
  0x201E: 0x84, // „
  0x2026: 0x85, // …
  0x2020: 0x86, // †
  0x2021: 0x87, // ‡
  0x02C6: 0x88, // ˆ
  0x2030: 0x89, // ‰
  0x0160: 0x8A, // Š
  0x2039: 0x8B, // ‹
  0x0152: 0x8C, // Œ
  0x017D: 0x8E, // Ž
  0x2018: 0x91, // ‘
  0x2019: 0x92, // ’
  0x201C: 0x93, // “
  0x201D: 0x94, // ”
  0x2022: 0x95, // •
  0x2013: 0x96, // –
  0x2014: 0x97, // —
  0x02DC: 0x98, // ˜
  0x2122: 0x99, // ™
  0x0161: 0x9A, // š
  0x203A: 0x9B, // ›
  0x0153: 0x9C, // œ
  0x017E: 0x9E, // ž
  0x0178: 0x9F, // Ÿ
};

/// [text] as Windows-1252 bytes, the encoding Excel in Brazil and the Android
/// Sheets app assume for a CSV file. Each character outside it (an emoji, an
/// alphabet other than Latin) becomes a question mark.
List<int> encodeWindows1252(String text) {
  final bytes = <int>[];
  for (final rune in text.runes) {
    if (rune < 0x80 || (rune >= 0xA0 && rune <= 0xFF)) {
      bytes.add(rune);
    } else {
      bytes.add(_windows1252Extras[rune] ?? 0x3F);
    }
  }
  return bytes;
}